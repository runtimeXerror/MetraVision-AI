/**
 * ── THE RULE VERSIONS ───────────────────────────────────────────────────────
 *
 * Each entry is one version of one requirement, with the text as it read while
 * that version was in force.
 *
 * The rule to hold on to while reading this file: **a version's `effectiveTo`
 * is the next version's `effectiveFrom`**, and the last version of a live
 * requirement has `effectiveTo: null`. `VersionResolver` picks by date and by
 * nothing else, so a chain that is right here is right everywhere, and a chain
 * that is wrong here is caught by `RuleSetValidator` before it can decide
 * anything.
 *
 * `legalText` is transcribed from the Gazette. Where a version was produced by
 * an amendment, it is the provision *as amended* — the reader should be able to
 * hold this next to the package and not have to reconstruct anything.
 *
 * `machineInterpretation` is narrower than the law, always, and says so. Rule
 * 6(1)(a) requires a name and address; the engine checks that something was
 * declared and that it looks like a name and address. It cannot check that the
 * address is the manufacturer's, and nothing here pretends otherwise.
 * ────────────────────────────────────────────────────────────────────────────
 */

/** Builds the `source` block from the amendment registry, so the two cannot drift. */
function src(notification: string): RuleSource {
  const amendment = findAmendment(notification);
  if (!amendment) {
    // A rule citing a notification with no registry entry is a corpus defect.
    // Fail loudly at module load rather than serve a rule with no provenance.
    throw new Error(`Rule cites ${notification}, which is not in the amendment registry.`);
  }
  return {
    authority: AUTHORITY,
    notification: amendment.notificationNumber,
    notificationDate: amendment.notificationDate,
    publicationDate: amendment.publicationDate,
    officialUrl: amendment.officialSourceUrl,
    verificationStatus: amendment.verificationStatus,
    verificationNote: amendment.verificationNote,
  };
}

